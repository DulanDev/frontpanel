/** One path per glyph: every horizontal run of lit pixels becomes a 1 px tall rectangle. */
export function toPath(rows: readonly string[]): string {
  let d = ''
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      if (row[x] !== '#') {
        x++
        continue
      }
      const start = x
      while (row[x] === '#')
        x++
      const run = x - start
      d += `M${start} ${y}h${run}v1h-${run}z`
    }
  })
  return d
}

/** Every icon name, in the order the set lists them. */
export const fpIconNames = Object.keys(BITMAPS) as FpIconName[]

/** The SVG path of each icon, on a 16 × 16 viewBox. */
export const fpIconPaths = Object.fromEntries(
  fpIconNames.map(name => [name, toPath(BITMAPS[name])]),
) as Record<FpIconName, string>
