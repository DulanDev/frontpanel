import type { Sources } from './generate.ts'
import { describe, expect, it } from 'vitest'
import { generate } from './generate.ts'

// Whitespace is not part of the contract: compare with every run of it collapsed to one space.
function squish(css: string): string {
  return css.replace(/\s+/g, ' ').trim()
}

function sources(overrides: Partial<Sources> = {}): Sources {
  return {
    utilities: '',
    shared: '',
    tokens: { silver: {}, gunmetal: {} },
    page: { utilities: '', shared: '' },
    ...overrides,
  }
}

const button = `
/** A push button. */
@utility fp-btn {
  color: var(--fp-color-ink);

  @media (pointer: fine) {
    min-height: 2.25rem;
  }

  &:hover:not(:disabled) {
    filter: brightness(1.05);
  }

  &[aria-pressed="true"] {
    translate: 0 1px;
  }
}
`

const shared = `
@keyframes fp-blink {
  50% { opacity: 0; }
}

.fp-sheet-enter-from {
  opacity: 0;
}
`

const tokens = {
  silver: { 'color-ink': '#1a1f29', 'color-shell': '#bcc5d1', 'font-lcd': '"VT323", monospace' },
  gunmetal: { 'color-ink': '#e7eaf0', 'color-shell': '#22262e' },
}

describe('every output', () => {
  it.each(['tokens.css', 'components.css', 'tailwind.css'] as const)('%s opens with a banner saying it is generated', (file) => {
    const css = generate(sources({ utilities: button, shared, tokens }))[file]

    expect(css).toMatch(/^\/\* Generated by scripts\/build\.ts from src\/\. Do not edit; edit the source and run `pnpm build`\. \*\/\n/)
  })
})

describe('components.css', () => {
  it('turns each utility into an .fp-* class inside @layer frontpanel, nesting intact', () => {
    const css = squish(generate(sources({ utilities: button }))['components.css'])

    expect(css).toContain(squish(`
      @layer frontpanel {
        /** A push button. */
        .fp-btn {
          color: var(--fp-color-ink);
          @media (pointer: fine) { min-height: 2.25rem; }
          &:hover:not(:disabled) { filter: brightness(1.05); }
          &[aria-pressed="true"] { translate: 0 1px; }
        }
      }
    `))
  })

  it('puts the shared rules inside the same layer, before the classes', () => {
    const css = squish(generate(sources({ utilities: button, shared }))['components.css'])

    expect(css).toMatch(/@layer frontpanel \{ @keyframes fp-blink \{ .*? \} \.fp-sheet-enter-from \{ opacity: 0; \} \/\*\* A push button\. \*\/ \.fp-btn \{/)
  })

  it('indents multi-line selectors and block comments to their new depth', () => {
    const shared = [
      '/*',
      ' * Two steps.',
      ' */',
      '@keyframes fp-x {',
      '  0%,',
      '  100% {',
      '    opacity: 1;',
      '  }',
      '}',
      '',
      '.fp-a,',
      '.fp-b {',
      '  opacity: 0;',
      '}',
    ].join('\n')

    expect(generate(sources({ shared }))['components.css'].split('\n').slice(1)).toEqual([
      '@layer frontpanel {',
      '  /*',
      '   * Two steps.',
      '   */',
      '  @keyframes fp-x {',
      '    0%,',
      '    100% {',
      '      opacity: 1;',
      '    }',
      '  }',
      '',
      '  .fp-a,',
      '  .fp-b {',
      '    opacity: 0;',
      '  }',
      '}',
      '',
    ])
  })

  it('indents multi-line values and doc comments to their new depth, so the file reads as written', () => {
    const utilities = [
      '/**',
      ' * A panel.',
      ' */',
      '@utility fp-panel {',
      '  box-shadow:',
      '    0 0 0 1px var(--fp-color-edge),',
      '    2px 3px 0 var(--fp-color-cast);',
      '}',
    ].join('\n')

    expect(generate(sources({ utilities }))['components.css'].split('\n').slice(1)).toEqual([
      '@layer frontpanel {',
      '  /**',
      '   * A panel.',
      '   */',
      '  .fp-panel {',
      '    box-shadow:',
      '      0 0 0 1px var(--fp-color-edge),',
      '      2px 3px 0 var(--fp-color-cast);',
      '  }',
      '}',
      '',
    ])
  })
})

const field = `
/** A text field. */
@utility fp-field {
  min-height: 2.75rem;
}
`

describe('page.css', () => {
  it('turns the page utilities into .fp-* classes in @layer frontpanel, after the page shared rules, and keeps them out of components.css', () => {
    const outputs = generate(sources({ utilities: button, page: { utilities: field, shared } }))

    expect(squish(outputs['page.css'])).toMatch(/@layer frontpanel \{ @keyframes fp-blink \{ .*? \} \.fp-sheet-enter-from \{ opacity: 0; \} \/\*\* A text field\. \*\/ \.fp-field \{ min-height: 2\.75rem; \} \}/)
    expect(outputs['components.css']).not.toContain('fp-field')
    expect(outputs['components.css']).not.toContain('fp-sheet')
  })
})

describe('tailwind-page.css', () => {
  it('holds the page shared rules in Tailwind\'s components layer and the page utilities, and leaves the tokens to tailwind.css', () => {
    const outputs = generate(sources({ utilities: button, tokens, page: { utilities: field, shared } }))
    const css = squish(outputs['tailwind-page.css'])

    expect(css).toContain('@layer components { @keyframes fp-blink { 50% { opacity: 0; } } .fp-sheet-enter-from { opacity: 0; } }')
    expect(css).toContain('/** A text field. */ @utility fp-field { min-height: 2.75rem; }')
    expect(css).not.toContain('@import')
    expect(css).not.toContain('@theme')
    expect(outputs['tailwind.css']).not.toContain('fp-field')
  })
})

describe('rejected source', () => {
  it.each([
    ['@apply', '@apply flex;'],
    ['@variant', '@variant hover { color: red; }'],
    ['--value()', 'width: --value(integer);'],
    ['--modifier()', 'opacity: --modifier(integer);'],
    ['--alpha()', 'color: --alpha(var(--fp-color-ink) / 50%);'],
    ['--spacing()', 'padding: --spacing(2);'],
    ['theme()', '@media (width >= theme(--breakpoint-lg)) { color: red; }'],
    ['--theme()', 'width: --theme(--breakpoint-lg);'],
  ])('fails on %s, which has no plain-CSS form', (construct, body) => {
    expect(() => generate(sources({ utilities: `@utility fp-x { ${body} }` })))
      .toThrow(`fp-x: ${construct} has no plain-CSS form`)
  })

  it.each([
    ['a name without the fp- prefix', '@utility btn { color: red; }', 'btn: utility names start with fp-'],
    ['a functional name', '@utility fp-gap-* { gap: 1px; }', 'fp-gap-*: functional utilities have no plain-CSS form'],
    ['a name used twice', '@utility fp-x { color: red; } @utility fp-x { color: blue; }', 'fp-x: defined twice'],
    ['a name that is a selector list', '@utility fp-x, .evil { color: red; }', 'fp-x, .evil: utility names are fp- then lowercase letters, digits and dashes'],
    ['a utility nested in another', '@utility fp-a { color: red; @utility fp-b { color: blue; } }', 'fp-a: a nested @utility is not allowed; declare fp-b at the top level'],
    ['a name with a pseudo-class', '@utility fp-x:hover { color: red; }', 'fp-x:hover: utility names are fp- then lowercase letters, digits and dashes'],
  ])('fails on %s', (_case, utilities, message) => {
    expect(() => generate(sources({ utilities }))).toThrow(message)
  })

  it.each([
    ['a plain rule', '.fp-x { color: red; }', '.fp-x'],
    ['keyframes', '@keyframes fp-x { to { opacity: 0; } }', '@keyframes fp-x'],
    ['a Tailwind directive', '@custom-variant dark (&:where(.dark, .dark *));', '@custom-variant dark (&:where(.dark, .dark *))'],
  ])('fails on %s at the top level of the utilities', (_case, utilities, found) => {
    expect(() => generate(sources({ utilities }))).toThrow(`utilities.css holds only @utility blocks and comments, found ${found}`)
  })

  it.each([
    ['Tailwind-only syntax', '.fp-x { @apply flex; }', 'shared.css: @apply has no plain-CSS form'],
    ['a Tailwind function', '.fp-x { width: --value(integer); }', 'shared.css: --value() has no plain-CSS form'],
    ['a Tailwind directive', '@utility fp-x { color: red; }', 'shared.css: @utility has no plain-CSS form'],
    ['a class without the prefix', '.btn { color: red; }', 'shared.css: .btn is not scoped to fp- classes'],
    ['an element selector, a global side effect', 'html { color: red; }', 'shared.css: html is not scoped to fp- classes'],
    ['a stray class inside an fp- selector', '.fp-a .btn { color: red; }', 'shared.css: .fp-a .btn is not scoped to fp- classes'],
    ['a rule inside @media', '@media (prefers-reduced-motion: reduce) { .btn { color: red; } }', 'shared.css: .btn is not scoped to fp- classes'],
    ['keyframes without the prefix', '@keyframes blink { to { opacity: 0; } }', 'shared.css: keyframes blink is not fp- prefixed'],
  ])('fails on %s in shared.css', (_case, shared, message) => {
    expect(() => generate(sources({ shared }))).toThrow(message)
  })

  it('accepts shared rules scoped to fp- classes, with keyframe steps and @media', () => {
    expect(() => generate(sources({ shared: `${shared} @media (pointer: fine) { .fp-sheet-enter-from:hover, .fp-a > .fp-b { translate: 6px 0; } }` }))).not.toThrow()
  })

  it.each([
    ['silver', { silver: { 'color-ink': '#1a1f29', 'color-label': 'var(--fp-color-ink)' }, gunmetal: {} }],
    ['gunmetal', { silver: { 'color-ink': '#1a1f29', 'color-label': '#1a1f29' }, gunmetal: { 'color-label': 'var(--fp-color-ink)' } }],
  ])('fails on a %s token that reads another with var(), which resolves where declared and so ignores a nested skin', (_skin, tokens) => {
    expect(() => generate(sources({ tokens }))).toThrow('color-label: token values are literals, not var()')
  })

  it.each([
    ['radius-btn', 'radius-btn: token names start with color- or font-'],
    ['font-size-lcd', 'font-size-lcd: font- tokens name font families, not sizes or weights'],
    ['font-weight-bold', 'font-weight-bold: font- tokens name font families, not sizes or weights'],
  ])('fails on the token name %s, which has no Tailwind mapping', (name, message) => {
    expect(() => generate(sources({ tokens: { silver: { [name]: '1px' }, gunmetal: {} } }))).toThrow(message)
  })

  it.each([
    ['a range width query', { utilities: '@utility fp-x { @media (width >= 64rem) { color: red; } }' }, 'fp-x'],
    ['a min-width query', { utilities: '@utility fp-x { @media (min-width: 600px) { color: red; } }' }, 'fp-x'],
    ['a height query', { utilities: '@utility fp-x { @media (max-height: 500px) { color: red; } }' }, 'fp-x'],
    ['an orientation query', { utilities: '@utility fp-x { @media (orientation: portrait) { color: red; } }' }, 'fp-x'],
    ['an aspect-ratio query', { utilities: '@utility fp-x { @media (min-aspect-ratio: 16/9) { color: red; } }' }, 'fp-x'],
    ['a breakpoint in the core shared rules', { shared: '@media (width >= 64rem) { .fp-x { color: red; } }' }, 'shared.css'],
  ])('fails on %s in the core, which would tie the device to a page layout', (_case, core, label) => {
    expect(() => generate(sources(core))).toThrow(`${label}: core classes carry no viewport breakpoints, found @media`)
  })

  it('allows viewport breakpoints in the page extra, and container and input queries in the core', () => {
    const page = { utilities: '@utility fp-p { @media (width >= 64rem) { color: red; } }', shared: '@media (width >= 64rem) { .fp-q { color: red; } }' }
    const utilities = '@utility fp-x { @container (width >= 20rem) { color: red; } @media (pointer: fine) { color: blue; } @media (prefers-reduced-motion: reduce) { color: green; } }'

    expect(() => generate(sources({ utilities, page }))).not.toThrow()
  })

  it('fails on a name used in both the core and the page extra', () => {
    const page = { utilities: '@utility fp-x { color: blue; }', shared: '' }

    expect(() => generate(sources({ utilities: '@utility fp-x { color: red; }', page }))).toThrow('fp-x: defined twice')
  })

  it('names the page file in a page error', () => {
    const page = { utilities: '.fp-x { color: red; }', shared: 'html { color: red; }' }

    expect(() => generate(sources({ page: { ...page, shared: '' } }))).toThrow('page/utilities.css holds only @utility blocks and comments, found .fp-x')
    expect(() => generate(sources({ page: { ...page, utilities: '' } }))).toThrow('page/shared.css: html is not scoped to fp- classes')
  })

  it('fails on a gunmetal token that silver does not define, since silver is the full set', () => {
    const tokens = { silver: { 'color-ink': '#1a1f29' }, gunmetal: { 'color-ink': '#e7eaf0', 'color-inc': '#e7eaf0' } }

    expect(() => generate(sources({ tokens }))).toThrow('color-inc: gunmetal sets a token silver does not define')
  })
})

describe('tokens.css', () => {
  it('sets the silver tokens on the root and on any [data-fp-skin="silver"] element', () => {
    const css = squish(generate(sources({ tokens }))['tokens.css'])

    expect(css).toContain('@layer frontpanel {')
    expect(css).toContain(squish(`
      :root, [data-fp-skin="silver"] {
        --fp-color-ink: #1a1f29;
        --fp-color-shell: #bcc5d1;
        --fp-font-lcd: "VT323", monospace;
      }
    `))
  })

  it('sets the gunmetal overrides for a dark system unless forced silver, and for any [data-fp-skin="gunmetal"] element', () => {
    const css = squish(generate(sources({ tokens }))['tokens.css'])
    const gunmetal = '--fp-color-ink: #e7eaf0; --fp-color-shell: #22262e;'

    expect(css).toContain(`@media (prefers-color-scheme: dark) { :root:not([data-fp-skin="silver"]) { ${gunmetal} } }`)
    expect(css).toContain(`[data-fp-skin="gunmetal"] { ${gunmetal} }`)
  })
})

describe('tailwind.css', () => {
  it('imports the tokens into Tailwind\'s theme layer and maps colours and fonts so bg-fp-shell follows the skin', () => {
    const css = squish(generate(sources({ tokens }))['tailwind.css'])

    expect(css).toContain('@import "./tokens.css" layer(theme);')
    expect(css).toContain(squish(`
      @theme inline {
        --color-fp-ink: var(--fp-color-ink);
        --color-fp-shell: var(--fp-color-shell);
        --font-fp-lcd: var(--fp-font-lcd);
      }
    `))
  })

  it('keeps @theme a block when there are no tokens', () => {
    expect(squish(generate(sources())['tailwind.css'])).toContain('@theme inline { }')
  })

  it('puts the shared rules in Tailwind\'s components layer, below its utilities', () => {
    const css = squish(generate(sources({ shared }))['tailwind.css'])

    expect(css).toContain('@layer components { @keyframes fp-blink { 50% { opacity: 0; } } .fp-sheet-enter-from { opacity: 0; } }')
  })

  it('keeps each utility as @utility fp-*, so Tailwind variants like lg: work on it', () => {
    const css = squish(generate(sources({ utilities: button }))['tailwind.css'])

    expect(css).toContain(squish(`
      /** A push button. */
      @utility fp-btn {
        color: var(--fp-color-ink);
        @media (pointer: fine) { min-height: 2.25rem; }
        &:hover:not(:disabled) { filter: brightness(1.05); }
        &[aria-pressed="true"] { translate: 0 1px; }
      }
    `))
  })
})
