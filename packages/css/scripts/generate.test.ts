import type { Sources } from './generate.ts'
import { describe, expect, it } from 'vitest'
import { generate } from './generate.ts'

// Whitespace is not part of the contract: compare with every run of it collapsed to one space.
function squish(css: string): string {
  return css.replace(/\s+/g, ' ').trim()
}

function sources(overrides: Partial<Sources> = {}): Sources {
  return {
    utilities: '',
    shared: '',
    tokens: { silver: {}, gunmetal: {} },
    ...overrides,
  }
}

const button = `
/** A push button. */
@utility fp-btn {
  color: var(--fp-color-ink);

  @media (width >= 64rem) {
    min-height: 2.25rem;
  }

  &:hover:not(:disabled) {
    filter: brightness(1.05);
  }

  &[aria-pressed="true"] {
    translate: 0 1px;
  }
}
`

const shared = `
@keyframes fp-blink {
  50% { opacity: 0; }
}

.fp-sheet-enter-from {
  opacity: 0;
}
`

const tokens = {
  silver: { 'color-ink': '#1a1f29', 'color-shell': '#bcc5d1', 'font-lcd': '"VT323", monospace' },
  gunmetal: { 'color-ink': '#e7eaf0', 'color-shell': '#22262e' },
}

describe('every output', () => {
  it.each(['tokens.css', 'components.css', 'tailwind.css'] as const)('%s opens with a banner saying it is generated', (file) => {
    const css = generate(sources({ utilities: button, shared, tokens }))[file]

    expect(css).toMatch(/^\/\* Generated by scripts\/build\.ts from src\/\. Do not edit; edit the source and run `pnpm build`\. \*\/\n/)
  })
})

describe('components.css', () => {
  it('turns each utility into an .fp-* class inside @layer frontpanel, nesting intact', () => {
    const css = squish(generate(sources({ utilities: button }))['components.css'])

    expect(css).toContain(squish(`
      @layer frontpanel {
        /** A push button. */
        .fp-btn {
          color: var(--fp-color-ink);
          @media (width >= 64rem) { min-height: 2.25rem; }
          &:hover:not(:disabled) { filter: brightness(1.05); }
          &[aria-pressed="true"] { translate: 0 1px; }
        }
      }
    `))
  })

  it('puts the shared rules inside the same layer, before the classes', () => {
    const css = squish(generate(sources({ utilities: button, shared }))['components.css'])

    expect(css).toMatch(/@layer frontpanel \{ @keyframes fp-blink \{ .*? \} \.fp-sheet-enter-from \{ opacity: 0; \} \/\*\* A push button\. \*\/ \.fp-btn \{/)
  })

  it('indents multi-line values and doc comments to their new depth, so the file reads as written', () => {
    const utilities = [
      '/**',
      ' * A panel.',
      ' */',
      '@utility fp-panel {',
      '  box-shadow:',
      '    0 0 0 1px var(--fp-color-edge),',
      '    2px 3px 0 var(--fp-color-cast);',
      '}',
    ].join('\n')

    expect(generate(sources({ utilities }))['components.css'].split('\n').slice(1)).toEqual([
      '@layer frontpanel {',
      '  /**',
      '   * A panel.',
      '   */',
      '  .fp-panel {',
      '    box-shadow:',
      '      0 0 0 1px var(--fp-color-edge),',
      '      2px 3px 0 var(--fp-color-cast);',
      '  }',
      '}',
      '',
    ])
  })
})

describe('rejected source', () => {
  it.each([
    ['@apply', '@apply flex;'],
    ['@variant', '@variant hover { color: red; }'],
    ['--value()', 'width: --value(integer);'],
    ['--modifier()', 'opacity: --modifier(integer);'],
    ['--alpha()', 'color: --alpha(var(--fp-color-ink) / 50%);'],
    ['--spacing()', 'padding: --spacing(2);'],
    ['theme()', '@media (width >= theme(--breakpoint-lg)) { color: red; }'],
    ['--theme()', 'width: --theme(--breakpoint-lg);'],
  ])('fails on %s, which has no plain-CSS form', (construct, body) => {
    expect(() => generate(sources({ utilities: `@utility fp-x { ${body} }` })))
      .toThrow(`fp-x: ${construct} has no plain-CSS form`)
  })

  it.each([
    ['a name without the fp- prefix', '@utility btn { color: red; }', 'btn: utility names start with fp-'],
    ['a functional name', '@utility fp-gap-* { gap: 1px; }', 'fp-gap-*: functional utilities have no plain-CSS form'],
    ['a name used twice', '@utility fp-x { color: red; } @utility fp-x { color: blue; }', 'fp-x: defined twice'],
  ])('fails on %s', (_case, utilities, message) => {
    expect(() => generate(sources({ utilities }))).toThrow(message)
  })

  it.each([
    ['a plain rule', '.fp-x { color: red; }', '.fp-x'],
    ['keyframes', '@keyframes fp-x { to { opacity: 0; } }', '@keyframes fp-x'],
    ['a Tailwind directive', '@custom-variant dark (&:where(.dark, .dark *));', '@custom-variant dark (&:where(.dark, .dark *))'],
  ])('fails on %s at the top level of the utilities', (_case, utilities, found) => {
    expect(() => generate(sources({ utilities }))).toThrow(`utilities.css holds only @utility blocks and comments, found ${found}`)
  })

  it('fails on a gunmetal token that silver does not define, since silver is the full set', () => {
    const tokens = { silver: { 'color-ink': '#1a1f29' }, gunmetal: { 'color-ink': '#e7eaf0', 'color-inc': '#e7eaf0' } }

    expect(() => generate(sources({ tokens }))).toThrow('color-inc: gunmetal sets a token silver does not define')
  })
})

describe('tokens.css', () => {
  it('sets the silver tokens on the root and on any [data-fp-skin="silver"] element', () => {
    const css = squish(generate(sources({ tokens }))['tokens.css'])

    expect(css).toContain('@layer frontpanel {')
    expect(css).toContain(squish(`
      :root, [data-fp-skin="silver"] {
        --fp-color-ink: #1a1f29;
        --fp-color-shell: #bcc5d1;
        --fp-font-lcd: "VT323", monospace;
      }
    `))
  })

  it('sets the gunmetal overrides for a dark system unless forced silver, and for any [data-fp-skin="gunmetal"] element', () => {
    const css = squish(generate(sources({ tokens }))['tokens.css'])
    const gunmetal = '--fp-color-ink: #e7eaf0; --fp-color-shell: #22262e;'

    expect(css).toContain(`@media (prefers-color-scheme: dark) { :root:not([data-fp-skin="silver"]) { ${gunmetal} } }`)
    expect(css).toContain(`[data-fp-skin="gunmetal"] { ${gunmetal} }`)
  })
})

describe('tailwind.css', () => {
  it('imports the tokens into Tailwind\'s theme layer and maps colours and fonts so bg-fp-shell follows the skin', () => {
    const css = squish(generate(sources({ tokens }))['tailwind.css'])

    expect(css).toContain('@import "./tokens.css" layer(theme);')
    expect(css).toContain(squish(`
      @theme inline {
        --color-fp-ink: var(--fp-color-ink);
        --color-fp-shell: var(--fp-color-shell);
        --font-fp-lcd: var(--fp-font-lcd);
      }
    `))
  })

  it('puts the shared rules in Tailwind\'s components layer, below its utilities', () => {
    const css = squish(generate(sources({ shared }))['tailwind.css'])

    expect(css).toContain('@layer components { @keyframes fp-blink { 50% { opacity: 0; } } .fp-sheet-enter-from { opacity: 0; } }')
  })

  it('keeps each utility as @utility fp-*, so Tailwind variants like lg: work on it', () => {
    const css = squish(generate(sources({ utilities: button }))['tailwind.css'])

    expect(css).toContain(squish(`
      /** A push button. */
      @utility fp-btn {
        color: var(--fp-color-ink);
        @media (width >= 64rem) { min-height: 2.25rem; }
        &:hover:not(:disabled) { filter: brightness(1.05); }
        &[aria-pressed="true"] { translate: 0 1px; }
      }
    `))
  })
})
